#!/usr/bin/env python3
"""Generate docs/CRATES.md (workspace crate list with roles and internal dependencies).

    python scripts/gen_crates_doc.py          # rewrite the file
    python scripts/gen_crates_doc.py --check  # exit 1 when the file is out of date

Roles come from the first `//!` line of each crate root, so the table cannot drift
from the code. Line counts are deliberately not included (they change on every edit).
"""
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "CRATES.md"


def crate_role(manifest_dir: pathlib.Path, src_path: pathlib.Path) -> str:
    """First paragraph of the crate-level `//!` documentation, on one line."""
    paragraph = []
    for line in src_path.read_text(encoding="utf-8").splitlines():
        if line.startswith("//!"):
            text = line[3:].strip()
            if text:
                paragraph.append(text)
            elif paragraph:
                break
        elif line.strip() and not line.startswith("#!"):
            break
        elif paragraph:
            break
    return " ".join(paragraph) or "(no crate-level documentation)"


def render() -> str:
    meta = json.loads(
        subprocess.check_output(["cargo", "metadata", "--no-deps", "--format-version", "1"], cwd=ROOT)
    )
    members = {p["name"]: p for p in meta["packages"]}
    rows = []
    for name in sorted(members):
        pkg = members[name]
        internal = sorted(d["name"] for d in pkg["dependencies"] if d["name"] in members and d["kind"] is None)
        target = next(t for t in pkg["targets"] if "lib" in t["kind"] or "proc-macro" in t["kind"] or "bin" in t["kind"])
        role = crate_role(pathlib.Path(pkg["manifest_path"]).parent, pathlib.Path(target["src_path"]))
        kind = "lib" if "lib" in target["kind"] else target["kind"][0]
        deps = ", ".join(f"`{d}`" for d in internal) or "-"
        rows.append(f"| `{name}` | {kind} | {role} | {deps} |")
    lines = [
        "# Workspace crates",
        "",
        "Generated by `scripts/gen_crates_doc.py` - do not edit by hand (CI runs it with `--check`).",
        "",
        "| Crate | Kind | Role | Internal dependencies |",
        "|---|---|---|---|",
        *rows,
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/CRATES.md is out of date; run: python scripts/gen_crates_doc.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


sys.exit(main())
